import 'dart:convert';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

class LocalDiagnosticReport extends StatefulWidget {
  const LocalDiagnosticReport({super.key});

  @override
  State<LocalDiagnosticReport> createState() => _LocalDiagnosticReportState();
}

class _LocalDiagnosticReportState extends State<LocalDiagnosticReport> {
  Map<String, dynamic>? _report;
  String? _error;
  int _selected = 0;

  Future<void> _import() async {
    try {
      final clipboard = await Clipboard.getData(Clipboard.kTextPlain);
      final report = jsonDecode(clipboard?.text ?? '') as Map<String, dynamic>;
      final runs = report['runs'] as List<dynamic>;
      if (report['schema'] != 1 ||
          report['vehicle'] is! String ||
          runs.isEmpty) {
        throw const FormatException();
      }
      for (final run in runs.cast<Map<String, dynamic>>()) {
        if (run['session'] is! String || run['windows'] is! int) {
          throw const FormatException();
        }
        for (final check in (run['checks'] as Map).values) {
          if (check is! Map ||
              check['scored'] is! int ||
              check['name'] is! String) {
            throw const FormatException();
          }
        }
        (run['events'] as List).cast<Map<String, dynamic>>().toList();
      }
      if (!mounted) return;
      setState(() {
        _report = report;
        _selected = 0;
        _error = null;
      });
    } on Exception {
      if (!mounted) return;
      setState(
        () => _error = 'Copy a report generated by the local diagnostic tool, then try again.',
      );
    } on TypeError {
      if (!mounted) return;
      setState(
        () => _error =
            'This clipboard content is not a supported diagnostic report.',
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    final runs = _report?['runs'] as List<dynamic>?;
    final run = runs?[_selected] as Map<String, dynamic>?;
    final events =
        (run?['events'] as List?)?.cast<Map<String, dynamic>>() ?? [];
    final checks = (run?['checks'] as Map?)?.entries ?? const [];
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          'Recording diagnostics',
          style: Theme.of(context).textTheme.titleLarge,
        ),
        const SizedBox(height: 8),
        if (run == null)
          const Text(
            'Analyze a saved recording on your computer and paste the report here.',
          ),
        OutlinedButton.icon(
          onPressed: _import,
          icon: const Icon(Icons.content_paste),
          label: const Text('Paste diagnostic report'),
        ),
        if (_error != null) Text(_error!),
        if (run != null) ...[
          Text('${_report!['vehicle']} · Model v${_report!['model_version']}'),
          if (_report!['provisional'] == true)
            const Text('Provisional baseline · No separate calibration day.'),
          DropdownButton<int>(
            isExpanded: true,
            value: _selected,
            items: [
              for (var i = 0; i < runs!.length; i++)
                DropdownMenuItem(
                  value: i,
                  child: Text(
                    'Recording ${i + 1} · ${runs[i]['session']}',
                    overflow: TextOverflow.ellipsis,
                  ),
                ),
            ],
            onChanged: (value) {
              if (value != null) setState(() => _selected = value);
            },
          ),
          if (run['simulation'] != null)
            const Text(
              'Simulated replay · Readings were modified for this test.',
            ),
          if (run['used_for_fit_or_calibration'] == true)
            const Text(
              'This recording contributed to model training or calibration.',
            ),
          for (final entry in checks)
            ListTile(
              contentPadding: EdgeInsets.zero,
              title: Text('${entry.value['name']}'),
              subtitle: Text(
                '${entry.value['scored']} of ${run['windows']} windows scored'
                '\n${entry.value['valid'] ?? 0} windows with a valid sensor reading',
              ),
              trailing: Text(
                entry.value['scored'] == 0
                    ? 'Unavailable'
                    : events.any((event) => '${event['pid']}' == entry.key)
                    ? 'Needs review'
                    : 'No sustained alert',
              ),
            ),
          for (final event in events)
            ExpansionTile(
              title: Text('${event['signal']} · ${event['direction']}'),
              subtitle: Text('${event['context']} · ${event['detected_at']}'),
              children: [
                ListTile(
                  subtitle: Text(
                    'Observed ${event['observed']} ${event['unit']}. Expected '
                    '${event['expected']} ${event['unit']}. Alert threshold '
                    '${event['threshold']} ${event['unit']}.\n${event['suggested_check']}',
                  ),
                ),
                for (final code
                    in (event['related_session_codes'] as List? ?? []))
                  ListTile(
                    title: Text('${code['code']} · ${code['status']}'),
                    subtitle: Text('Scan: ${code['scan_time']}'),
                  ),
              ],
            ),
        ],
      ],
    );
  }
}
